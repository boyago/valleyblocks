import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdir} from 'node:fs/promises';
const require=createRequire(new URL('../../games/vale-dos-blocos/package.json',import.meta.url));
const {chromium}=require('playwright');
const origin=process.env.USAGE_PREVIEW_URL||'http://127.0.0.1:5194';
assert.ok(['127.0.0.1','localhost'].includes(new URL(origin).hostname),'This test only targets local preview');
const admin=process.env.TEST_ADMIN_USERNAME||'qa_admin';
const password=process.env.TEST_ADMIN_PASSWORD||'Local test-only password 2026!';
const browser=await chromium.launch({headless:true,channel:'msedge'});
const context=await browser.newContext({viewport:{width:1440,height:1050}});
const page=await context.newPage();const errors=[],events=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('request',r=>{if(r.url().endsWith('/api/game-usage')&&r.method()==='POST')events.push(r.postDataJSON());});
await mkdir('.local',{recursive:true});
try{
  let response=await context.request.get(origin+'/api/admin/game-usage');assert.equal(response.status(),401);
  response=await context.request.post(origin+'/api/game-usage',{data:{},headers:{Origin:'https://example.com'}});assert.equal(response.status(),403);
  response=await context.request.post(origin+'/api/game-usage',{data:{game:'bad'},headers:{Origin:origin}});assert.equal(response.status(),400);
  await page.goto(origin+'/jogos/vale-dos-blocos');
  await page.getByRole('button',{name:'Permitir métricas',exact:true}).click();
  await page.getByRole('button',{name:'Jogar agora',exact:true}).click();
  const frame=page.frameLocator('iframe[title="Vale dos Blocos"]');
  await frame.locator('[data-action="new-game"]').waitFor({timeout:45000});
  assert.equal(events.length,0,'Landing must not count as playing');
  const started=page.waitForResponse(r=>r.url().endsWith('/api/game-usage')&&r.request().postDataJSON().active);
  await frame.locator('[data-action="new-game"]').click();assert.equal((await started).status(),200);
  const login=await context.request.post(origin+'/api/account/login',{headers:{Origin:origin},data:{username:admin,password}});assert.equal(login.status(),200);
  const report=async()=>{const r=await context.request.get(origin+'/api/admin/game-usage');assert.equal(r.status(),200);return r.json();};
  let data=await report();assert.ok(data.active.some(r=>Number(r.players)>=1));
  const cookie=(await context.cookies()).find(c=>c.name==='labs_usage');assert.ok(cookie?.httpOnly);
  const stopped=page.waitForResponse(r=>r.url().endsWith('/api/game-usage')&&r.request().postDataJSON().active===false);
  await page.evaluate(()=>document.querySelector('iframe').contentWindow.postMessage({labs:1,type:'pause'},location.origin));
  assert.equal((await stopped).status(),200);data=await report();assert.equal(data.active.length,0);
  assert.ok(data.days.some(r=>Number(r.active_ms)>0));
  await page.goto(origin+'/admin/uso');await page.getByRole('button',{name:'Consultar',exact:true}).click();
  await page.getByText('Atividade diária autorizada',{exact:true}).waitFor();
  await page.screenshot({path:'.local/usage-dashboard-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile page has no horizontal overflow');
  await page.screenshot({path:'.local/usage-dashboard-mobile.png',fullPage:true});
  const logout=await context.request.post(origin+'/api/account/logout',{headers:{Origin:origin},data:{}});assert.equal(logout.status(),200);assert.equal((await context.request.get(origin+'/api/admin/game-usage')).status(),401);
  assert.deepEqual(errors,[]);
  console.log('PASS: API authorization/origin/validation, real start, landing excluded, pause, signed HttpOnly cookie, persisted report, dashboard desktop/mobile/logout; no runtime errors.');
}finally{await browser.close();}
